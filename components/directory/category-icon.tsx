// Por palabra clave dentro del slug de la categoría o industria.
const ICONS: Array<[string, LucideIcon]> = [
  ["hamburgues", Hamburger],
  ["pizza", Pizza],
  ["perro", Sandwich],
  ["sandwich", Sandwich],
  ["empanada", Croissant],
  ["panaderia", Croissant],
  ["pan", Croissant],
  ["postre", CakeSlice],
  ["helado", IceCreamCone],
  ["galleta", Cookie],
  ["cafe", Coffee],
  ["desayuno", EggFried],
  ["bebida", CupSoda],
  ["jugo", CupSoda],
  ["cerveza", Beer],
  ["licor", Wine],
  ["vino", Wine],
  ["pollo", Drumstick],
  ["alita", Drumstick],
  ["carne", Beef],
  ["parrilla", Beef],
  ["mar", Fish],
  ["pescado", Fish],
  ["sushi", Fish],
  ["ensalada", Salad],
  ["saludable", Salad],
  ["sopa", Soup],
  ["farmacia", Pill],
  ["medicamento", Pill],
  ["mascota", PawPrint],
  ["tienda", ShoppingBasket],
  ["mercado", ShoppingBasket],
];

export function categoryIcon(slug: string): LucideIcon {
  return ICONS.find(([key]) => slug.includes(key))?.[1] ?? UtensilsCrossed;
}
